/**
 * Generates the canonical anatomy asset manifest from the actual optimized
 * production GLBs (byte size + SHA-256 verified at generation time).
 *
 * Usage: node scripts/generate-anatomy-manifest.js
 *
 * Reads:  3d-assets/<bodyModel>/working/optimized/*.glb
 * Writes: frontend/packages/anatomy-core/src/assetManifest.ts
 *
 * Rules:
 * - Production identity is (bodyModel directory + unprefixed filename).
 * - Filenames must match `<system>-meshopt.glb` for a known system key.
 * - Any unexpected file, unknown system, duplicate, or empty file fails loudly.
 * - The manifest carries NO host/base URL: any ordinary HTTPS static host can
 *   serve it later (recommended layout documents host conventions only).
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const BODY_MODELS = ['male', 'female'];
const SYSTEM_ORDER = [
  'skin',
  'musculoskeletal',
  'nervous',
  'cardiovascular',
  'respiratory',
  'digestive',
  'urinary',
  'reproductive',
  'lymphatic',
];

function fail(message) {
  console.error(`generate-anatomy-manifest: ${message}`);
  process.exit(1);
}

function optimizedDir(bodyModel) {
  return path.join(ROOT, '3d-assets', bodyModel, 'working', 'optimized');
}

function parseEntry(bodyModel, filename) {
  const match = /^([a-z]+)-meshopt\.glb$/.exec(filename);
  if (!match) fail(`unexpected filename (not <system>-meshopt.glb): ${bodyModel}/${filename}`);
  const system = match[1];
  if (!SYSTEM_ORDER.includes(system)) fail(`unknown system key: ${bodyModel}/${filename}`);
  return system;
}

function sha256File(filePath) {
  const hash = crypto.createHash('sha256');
  const stat = fs.statSync(filePath);
  if (stat.size === 0) fail(`empty file: ${filePath}`);
  const fd = fs.openSync(filePath, 'r');
  try {
    const buffer = Buffer.alloc(1024 * 1024);
    let read = 0;
    while ((read = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0) {
      hash.update(buffer.subarray(0, read));
    }
  } finally {
    fs.closeSync(fd);
  }
  return { bytes: stat.size, sha256: hash.digest('hex') };
}

function main() {
  const entries = [];
  const seen = new Set();
  for (const bodyModel of BODY_MODELS) {
    const dir = optimizedDir(bodyModel);
    if (!fs.existsSync(dir)) fail(`missing optimized directory: ${dir}`);
    const files = fs.readdirSync(dir).filter(name => name.toLowerCase().endsWith('.glb'));
    for (const filename of files) {
      const system = parseEntry(bodyModel, filename);
      const key = `${bodyModel}/${system}`;
      if (seen.has(key)) fail(`duplicate entry: ${key}`);
      seen.add(key);
      const { bytes, sha256 } = sha256File(path.join(dir, filename));
      entries.push({ bodyModel, system, file: filename, bytes, sha256 });
    }
  }
  for (const bodyModel of BODY_MODELS) {
    for (const system of SYSTEM_ORDER) {
      if (!seen.has(`${bodyModel}/${system}`))
        fail(`missing production asset: ${bodyModel}/${system}`);
    }
  }
  entries.sort(
    (a, b) =>
      BODY_MODELS.indexOf(a.bodyModel) - BODY_MODELS.indexOf(b.bodyModel) ||
      SYSTEM_ORDER.indexOf(a.system) - SYSTEM_ORDER.indexOf(b.system)
  );

  const lines = [
    '/**',
    ' * GENERATED by scripts/generate-anatomy-manifest.js — do not edit by hand.',
    ' * Canonical production asset identities, byte sizes, and SHA-256 hashes,',
    ' * verified against the actual optimized GLBs at generation time.',
    ' *',
    ' * `file` is the production filename (unprefixed; identity is completed by',
    ' * `bodyModel`). Recommended static-host layout: `<base>/<bodyModel>/<file>`.',
    ' * Local dev serves a flat subset under `/models-dev/` with `female-`-prefixed',
    ' * copies — see devAssetFilename(). No host, backend, or database involved.',
    ' */',
    "import type { AnatomyBodyModelKey, AnatomySystemKey } from '@anatomiax/shared-types';",
    '',
    'export interface AssetManifestEntry {',
    '  bodyModel: AnatomyBodyModelKey;',
    '  system: AnatomySystemKey;',
    '  /** Production filename (unprefixed). */',
    '  file: string;',
    '  /** Exact byte size of the hashed file. */',
    '  bytes: number;',
    '  /** Lowercase hex SHA-256 of the exact file bytes. */',
    '  sha256: string;',
    '}',
    '',
    'export const ASSET_MANIFEST: readonly AssetManifestEntry[] = [',
    ...entries.flatMap(e => [
      '  {',
      `    bodyModel: '${e.bodyModel}',`,
      `    system: '${e.system}',`,
      `    file: '${e.file}',`,
      `    bytes: ${e.bytes},`,
      `    sha256: '${e.sha256}',`,
      '  },',
    ]),
    '];',
    '',
    'export function findManifestEntry(',
    '  bodyModel: AnatomyBodyModelKey,',
    '  system: AnatomySystemKey',
    '): AssetManifestEntry | undefined {',
    '  return ASSET_MANIFEST.find(e => e.bodyModel === bodyModel && e.system === system);',
    '}',
    '',
    '/**',
    ' * Local-dev flat-layout filename: male entries are served unprefixed while',
    ' * female entries are served as `female-<file>` under `/models-dev/`.',
    ' * Production/hosted layouts must use `file` (with `bodyModel` as identity).',
    ' */',
    'export function devAssetFilename(bodyModel: AnatomyBodyModelKey, file: string): string {',
    "  return bodyModel === 'female' ? `female-${file}` : file;",
    '}',
    '',
  ];
  const outPath = path.join(
    ROOT,
    'frontend',
    'packages',
    'anatomy-core',
    'src',
    'assetManifest.ts'
  );
  fs.writeFileSync(outPath, lines.join('\n'));
  console.log(`generate-anatomy-manifest: wrote ${entries.length} entries to ${outPath}`);
}

main();
